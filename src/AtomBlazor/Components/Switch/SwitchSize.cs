namespace AtomBlazor;

/// <summary>
/// 定义 Switch 组件的尺寸变体。
/// </summary>
public enum SwitchSize
{
    /// <summary>
    /// 小号开关（h-5 w-9，thumb h-4 w-4）。
    /// </summary>
    Small,

    /// <summary>
    /// 中号开关（默认）（h-6 w-11，thumb h-5 w-5）。
    /// </summary>
    Medium,

    /// <summary>
    /// 大号开关（h-7 w-14，thumb h-6 w-6）。
    /// </summary>
    Large
}
