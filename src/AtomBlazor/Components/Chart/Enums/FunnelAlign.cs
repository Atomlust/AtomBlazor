namespace AtomBlazor;

/// <summary>
/// 指定漏斗图各段（segment）的水平对齐方式。
/// </summary>
public enum FunnelAlign
{
    /// <summary>
    /// 各段水平居中。
    /// </summary>
    Center,

    /// <summary>
    /// 各段与左边缘对齐。
    /// </summary>
    Left,

    /// <summary>
    /// 各段与右边缘对齐。
    /// </summary>
    Right
}
