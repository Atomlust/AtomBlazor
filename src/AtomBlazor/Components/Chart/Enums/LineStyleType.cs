namespace AtomBlazor;

/// <summary>
/// 指定线的视觉样式（轴线、grid 分隔线、边框）。
/// </summary>
public enum LineStyleType
{
    /// <summary>
    /// 连续的实线。
    /// </summary>
    Solid,

    /// <summary>
    /// 虚线（grid 分隔线的默认值）。
    /// </summary>
    Dashed,

    /// <summary>
    /// 点线。
    /// </summary>
    Dotted
}
