namespace AtomBlazor;

/// <summary>
/// 定义 ItemMedia 组件的视觉风格变体。
/// </summary>
public enum ItemMediaVariant
{
    /// <summary>
    /// 默认变体，无特定样式。
    /// </summary>
    Default,

    /// <summary>
    /// 图标变体，带方形边框容器（8px）。
    /// </summary>
    Icon,

    /// <summary>
    /// 图片变体，带圆角容器（10px）。
    /// </summary>
    Image
}
