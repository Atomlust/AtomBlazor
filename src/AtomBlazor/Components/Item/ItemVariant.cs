namespace AtomBlazor;

/// <summary>
/// 定义 Item 组件的视觉风格变体。
/// </summary>
public enum ItemVariant
{
    /// <summary>
    /// 默认变体，无边框无背景。
    /// </summary>
    Default,

    /// <summary>
    /// 轮廓变体，带边框。
    /// </summary>
    Outline,

    /// <summary>
    /// 柔和变体，带浅色背景。
    /// </summary>
    Muted
}
