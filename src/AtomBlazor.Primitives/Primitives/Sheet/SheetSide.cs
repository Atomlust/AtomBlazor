namespace AtomBlazor.Primitives;

/// <summary>
/// 定义 Sheet 从哪一侧滑入。
/// </summary>
public enum SheetSide
{
    /// <summary>
    /// Sheet 从顶部边缘滑入。
    /// </summary>
    Top,

    /// <summary>
    /// Sheet 从右侧边缘滑入（默认）。
    /// </summary>
    Right,

    /// <summary>
    /// Sheet 从底部边缘滑入。
    /// </summary>
    Bottom,

    /// <summary>
    /// Sheet 从左侧边缘滑入。
    /// </summary>
    Left
}
