namespace AtomBlazor.Primitives;

/// <summary>
/// 定义滚动区域的可滚动朝向。
/// </summary>
public enum ScrollAreaOrientation
{
    /// <summary>
    /// 仅纵向滚动。
    /// </summary>
    Vertical,

    /// <summary>
    /// 仅横向滚动。
    /// </summary>
    Horizontal,

    /// <summary>
    /// 纵向与横向皆可滚动。
    /// </summary>
    Both
}
